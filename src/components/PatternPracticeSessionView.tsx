interface Props {
  pattern: LanguagePattern;
  sentenceIndex: number;
  groupIndex?: number;
  onBack: () => void;
  onNext: () => void;
  isLastSentence: boolean;
  progressLabel?: string;
  onScored?: (sentenceId: string, total: number) => void; // 每次評分完成時回報（維持複習用）
}

type SessionState = 'idle' | 'recording' | 'scoring' | 'scored' | 'scoreError';

type PromptType = 'qaQuestion' | 'situationalPrompt' | 'imageUrl';


function calculateMasteryAfterAttempt(
  currentMastery: number,
  nextAvailableAt: number | undefined,
  scoreTotal: number,
  now: number
): {
  newMastery: number;
  newNextAvailableAt: number | undefined;
  isBlockedByTier: boolean;
} {
  let currentTierLimit = 1000;
  let waitDays = 0;

  if (currentMastery < 250) {
    currentTierLimit = 250;
    waitDays = 2;
  } else if (currentMastery === 250) {
    if (nextAvailableAt === undefined || isSydneyDateReached(nextAvailableAt, now)) {
      currentTierLimit = 500;
      waitDays = 4;
    } else {
      currentTierLimit = 250;
    }
  } else if (currentMastery < 500) {
    currentTierLimit = 500;
    waitDays = 4;
  } else if (currentMastery === 500) {
    if (nextAvailableAt === undefined || isSydneyDateReached(nextAvailableAt, now)) {
      currentTierLimit = 750;
      waitDays = 8;
    } else {
      currentTierLimit = 500;
    }
  } else if (currentMastery < 750) {
    currentTierLimit = 750;
    waitDays = 8;
  } else if (currentMastery === 750) {
    if (nextAvailableAt === undefined || isSydneyDateReached(nextAvailableAt, now)) {
      currentTierLimit = 1000;
    } else {
      currentTierLimit = 750;
    }
  }

  const theoreticalScore = currentMastery + scoreTotal;

  if (theoreticalScore <= currentTierLimit) {
    return {
      newMastery: theoreticalScore,
      newNextAvailableAt: undefined,
      isBlockedByTier: false
    };
  } else {
    if (currentTierLimit === 1000) {
      return {
        newMastery: 1000,
        newNextAvailableAt: undefined,
        isBlockedByTier: false
      };
    }
    
    // hit limit
    const isAlreadyAtLimit = currentMastery === currentTierLimit;
    return {
      newMastery: currentTierLimit,
      newNextAvailableAt: isAlreadyAtLimit ? undefined : addSydneyCalendarDays(now, waitDays),
      isBlockedByTier: true
    };
  }
}

// 依 v1 規格：mastery 越高，越常出現難度高的題型（情境任務、圖片）
const pickPromptTypeByMastery = (available: PromptType[], mastery: number): PromptType => {
    let weights: Record<string, number>;
    if (mastery < 400) weights = { qaQuestion: 70, situationalPrompt: 20, imageUrl: 10 };
    else if (mastery < 700) weights = { qaQuestion: 40, situationalPrompt: 35, imageUrl: 25 };
    else weights = { qaQuestion: 15, situationalPrompt: 40, imageUrl: 45 };

    const total = available.reduce((sum, t) => sum + (weights[t] || 0), 0);
    let r = Math.random() * total;
    for (const t of available) {
        r -= weights[t] || 0;
        if (r < 0) return t;
    }
    return available[available.length - 1];
};

export default function PatternPracticeSessionView({ pattern, sentenceIndex, groupIndex, onBack, onNext, isLastSentence, progressLabel, onScored }: Props) {
    const [sessionState, setSessionState] = useState<SessionState>('idle');
    const [activePromptType, setActivePromptType] = useState<PromptType | null>(null);
    const [errorMsg, setErrorMsg] = useState<string | null>(null);
    const [scoreResult, setScoreResult] = useState<{ pronunciation: number, fluency: number, stress: number, total: number } | null>(null);
    const [userText, setUserText] = useState<string>('');
    const [currentMastery, setCurrentMastery] = useState<number>(0);
    const [tierBlockInfo, setTierBlockInfo] = useState<{ blocked: boolean, waitDays: number } | null>(null);
    const [isPromptReady, setIsPromptReady] = useState<boolean>(true);
    const [promptStatus, setPromptStatus] = useState<'idle' | 'generating' | 'error'>('idle');
    const [promptError, setPromptError] = useState<string | null>(null);
    const [generatedPrompts, setGeneratedPrompts] = useState<{ qaQuestion: string; situationalPrompt: string } | null>(null);
    const autoGeneratedForRef = useRef<string | null>(null);
    const imageRequestedForRef = useRef<string | null>(null);
    const speechAudioRef = useRef<HTMLAudioElement>(null);
    const answerAudioUrlRef = useRef<string | null>(null);
    const sessionStateRef = useRef<SessionState>('idle');
    const [promptAudioUrl, setPromptAudioUrl] = useState<string | null>(null);
    const [promptAudioLoading, setPromptAudioLoading] = useState(false);
    const [hasAnswerAudio, setHasAnswerAudio] = useState(false);

    const mediaRecorderRef = useRef<MediaRecorder | null>(null);
    const streamRef = useRef<MediaStream | null>(null);
    const audioContextRef = useRef<AudioContext | null>(null);
    const analyserRef = useRef<AnalyserNode | null>(null);
    const sourceRef = useRef<MediaStreamAudioSourceNode | null>(null);
    const silenceTimerRef = useRef<number>(0);
    const requestAnimationFrameRef = useRef<number>(0);
    const audioChunksRef = useRef<Blob[]>([]);
    const recordingStartTimeRef = useRef<number>(0);
    const recordedAudioRef = useRef<HTMLAudioElement>(null);
    const playbackUrlRef = useRef<string | null>(null);
    const lastRecordingRef = useRef<{ blob: Blob; durationSec: number } | null>(null);

    const sentences = pattern.exampleSentences || [];
    const sentenceObj = sentences[sentenceIndex];

    // 目前題目要朗讀的文字（看圖題沒有文字，不朗讀）
    const currentPromptText =
        activePromptType === 'qaQuestion' ? (sentenceObj?.qaQuestion || generatedPrompts?.qaQuestion || '') :
        activePromptType === 'situationalPrompt' ? (sentenceObj?.situationalPrompt || generatedPrompts?.situationalPrompt || '') :
        '';

    const stopSpeech = () => {
        const el = speechAudioRef.current;
        if (!el) return;
        el.onended = null;
        el.pause();
    };

    // 播放一段語音；播放失敗或播完時呼叫 onEnded
    const playSpeech = (url: string, onEnded?: () => void) => {
        const el = speechAudioRef.current;
        if (!el) {
            onEnded?.();
            return;
        }
        el.onended = onEnded ? () => { el.onended = null; onEnded(); } : null;
        el.src = url;
        el.currentTime = 0;
        el.play().catch(() => {
            el.onended = null;
            onEnded?.();
        });
    };

    const initPrompt = () => {
        if (!sentenceObj) return;
        const availablePrompts: PromptType[] = [];
        if (sentenceObj.qaQuestion) availablePrompts.push('qaQuestion');
        if (sentenceObj.situationalPrompt) availablePrompts.push('situationalPrompt');
        if (sentenceObj.imageUrl) availablePrompts.push('imageUrl');

        if (availablePrompts.length === 0) {
            setIsPromptReady(false);
            setActivePromptType(null);
        } else {
            setIsPromptReady(true);
            setActivePromptType(pickPromptTypeByMastery(availablePrompts, sentenceObj.mastery || 0));
        }
        setCurrentMastery(sentenceObj.mastery || 0);
    };

    const generatePrompts = async () => {
        if (!sentenceObj || promptStatus === 'generating') return;
        setPromptStatus('generating'); setPromptError(null);
        try {
            const prompts = await generateAndSavePracticePrompts(pattern.id, sentenceObj.id, sentenceObj.text, pattern.text);
            setGeneratedPrompts(prompts);
            const available: PromptType[] = ['qaQuestion', 'situationalPrompt'];
            if (sentenceObj.imageUrl) available.push('imageUrl');
            setActivePromptType(pickPromptTypeByMastery(available, sentenceObj.mastery || 0));
            setIsPromptReady(true);
            setPromptStatus('idle');
        } catch (err: any) {
            console.error('產生題目失敗:', err);
            setPromptError(err?.message || '產生題目失敗，請稍後再試');
            setPromptStatus('error');
        }
    };

    useEffect(() => {
        stopSpeech();
        if (recordedAudioRef.current) {
            recordedAudioRef.current.pause();
            recordedAudioRef.current.currentTime = 0;
        }
        lastRecordingRef.current = null;
        if (playbackUrlRef.current) {
            URL.revokeObjectURL(playbackUrlRef.current);
            playbackUrlRef.current = null;
        }
        setSessionState('idle');
        setScoreResult(null);
        setUserText('');
        setErrorMsg(null);
        setTierBlockInfo(null);
        setPromptStatus('idle'); setPromptError(null); setGeneratedPrompts(null);
        initPrompt();
    }, [pattern.id, sentenceIndex]);

    const cleanupAudio = () => {
        if (requestAnimationFrameRef.current) {
            cancelAnimationFrame(requestAnimationFrameRef.current);
            requestAnimationFrameRef.current = 0;
        }
        if (sourceRef.current) {
            sourceRef.current.disconnect();
            sourceRef.current = null;
        }
        if (analyserRef.current) {
            analyserRef.current.disconnect();
            analyserRef.current = null;
        }
        if (audioContextRef.current) {
            audioContextRef.current.close().catch(console.error);
            audioContextRef.current = null;
        }
        if (streamRef.current) {
            streamRef.current.getTracks().forEach(track => track.stop());
            streamRef.current = null;
        }
    };

    useEffect(() => {
        return () => {
            // 離開頁面時若仍在錄音，先移除 onstop 再停止，避免離開後仍在背景評分並寫入分數
            if (mediaRecorderRef.current && mediaRecorderRef.current.state === 'recording') {
                mediaRecorderRef.current.onstop = null;
                mediaRecorderRef.current.stop();
            }
            recordedAudioRef.current?.pause();
            if (speechAudioRef.current) {
                speechAudioRef.current.onended = null;
                speechAudioRef.current.pause();
            }
            if (playbackUrlRef.current) {
                URL.revokeObjectURL(playbackUrlRef.current);
                playbackUrlRef.current = null;
            }
            cleanupAudio();
        };
    }, []);

    useEffect(() => {
        sessionStateRef.current = sessionState;
    }, [sessionState]);

    // 題目朗讀：題目文字變了就取得語音，取得後在待機狀態自動播放一次
    // （iPhone 在使用者點擊畫面前會擋下自動播放，第一題可能需要手動按「播放題目」）
    useEffect(() => {
        let cancelled = false;
        setPromptAudioUrl(null);
        if (!currentPromptText) {
            setPromptAudioLoading(false);
            return;
        }
        setPromptAudioLoading(true);
        getSpeechUrl(currentPromptText).then(url => {
            if (cancelled) return;
            setPromptAudioLoading(false);
            setPromptAudioUrl(url);
            if (url && sessionStateRef.current === 'idle') {
                playSpeech(url);
            }
        });
        return () => { cancelled = true; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [currentPromptText]);

    // 預先取得正確答案（原句）的語音，評分後播放
    useEffect(() => {
        let cancelled = false;
        answerAudioUrlRef.current = null;
        setHasAnswerAudio(false);
        const text = sentenceObj?.text;
        if (!text) return;
        getSpeechUrl(text).then(url => {
            if (cancelled) return;
            answerAudioUrlRef.current = url;
            setHasAnswerAudio(!!url);
        });
        return () => { cancelled = true; };
    }, [sentenceObj?.text]);

    useEffect(() => {
        if (!isPromptReady && sentenceObj && autoGeneratedForRef.current !== sentenceObj.id) {
            autoGeneratedForRef.current = sentenceObj.id;
            generatePrompts();
        }
    // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [isPromptReady, sentenceObj?.id]);

    // 進入練習時，幫這一組還沒有圖的句子補產看圖題圖片（同一組只觸發一次）
    useEffect(() => {
        const g = groupIndex ?? sentenceObj?.groupIndex;
        if (g === undefined || g === null) return;
        const key = `${pattern.id}::${g}`;
        if (imageRequestedForRef.current === key) return;
        imageRequestedForRef.current = key;
        const ids = (pattern.exampleSentences || []).filter(s => s.groupIndex === g).map(s => s.id);
        void requestPracticeImages(pattern.id, ids);
    // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [pattern.id, groupIndex, sentenceObj?.groupIndex]);

    const monitorVolume = () => {
        if (!analyserRef.current) return;
        
        const analyser = analyserRef.current;
        const bufferLength = analyser.frequencyBinCount;
        const dataArray = new Uint8Array(bufferLength);
        analyser.getByteFrequencyData(dataArray);

        let sum = 0;
        for (let i = 0; i < bufferLength; i++) {
            sum += dataArray[i];
        }
        const averageVolume = sum / bufferLength;

        if (averageVolume < 20) {
            if (silenceTimerRef.current === 0) {
                silenceTimerRef.current = Date.now();
            } else if (Date.now() - silenceTimerRef.current > 1500) {
                // Silence detected for 1.5 seconds
                if (mediaRecorderRef.current && mediaRecorderRef.current.state === 'recording') {
                    mediaRecorderRef.current.stop();
                }
                return;
            }
        } else {
            silenceTimerRef.current = 0;
        }

        requestAnimationFrameRef.current = requestAnimationFrame(monitorVolume);
    };

    const runScoring = async (blob: Blob, durationSec: number) => {
        setSessionState('scoring');
        setErrorMsg(null);
        
        const file = new File([blob], 'record.webm', { type: blob.type });

        try {
            const transcribedText = await transcribeRecording(file);
            setUserText(transcribedText);
            const scores = calculateFinalScores(transcribedText, sentenceObj.text, durationSec);
            setScoreResult(scores);
            onScored?.(sentenceObj.id, scores.total);

            if (scores.total >= 70) {
                const uid = auth.currentUser?.uid;
                if (uid) {
                    const now = Date.now();
                    let outcome: { newMastery: number; newNextAvailableAt?: number; isBlockedByTier: boolean; oldNextAvailableAt?: number } | null = null;
                    await updatePatternSentences(pattern.id, (sentences) => {
                        const idx = sentences.findIndex(s => s.id === sentenceObj.id);
                        if (idx < 0) return null;
                        const s = sentences[idx];
                        const oldMastery = s.mastery || 0;
                        const oldNextAvailableAt = s.nextAvailableAt;
                        const r = calculateMasteryAfterAttempt(oldMastery, oldNextAvailableAt, scores.total, now);
                        sentences[idx] = { ...s, mastery: r.newMastery, ...(r.newNextAvailableAt !== undefined ? { nextAvailableAt: r.newNextAvailableAt } : {}) };
                        outcome = { newMastery: r.newMastery, newNextAvailableAt: r.newNextAvailableAt, isBlockedByTier: r.isBlockedByTier, oldNextAvailableAt };
                        return sentences;
                    });
                    if (outcome) {
                        setCurrentMastery(outcome.newMastery);
                        if (outcome.isBlockedByTier) {
                            const targetDate = outcome.newNextAvailableAt || outcome.oldNextAvailableAt || now;
                            const waitDays = getSydneyCalendarDaysDiff(now, targetDate);
                            setTierBlockInfo({ blocked: true, waitDays: waitDays > 0 ? waitDays : 1 });
                        } else {
                            setTierBlockInfo(null);
                        }
                    }
                }
            }
            setSessionState('scored');

            if (recordedAudioRef.current) {
                if (playbackUrlRef.current) {
                    URL.revokeObjectURL(playbackUrlRef.current);
                }
                const url = URL.createObjectURL(blob);
                playbackUrlRef.current = url;
                recordedAudioRef.current.src = url;
                recordedAudioRef.current.currentTime = 0;
                // 先播放正確答案，播完再播放自己的錄音；沒有答案語音時直接播錄音
                const playRecording = () => {
                    recordedAudioRef.current?.play().catch(() => {});
                };
                const answerUrl = answerAudioUrlRef.current;
                if (answerUrl) {
                    playSpeech(answerUrl, playRecording);
                } else {
                    playRecording();
                }
            }
        } catch (err: any) {
            console.error("Scoring error:", err);
            setErrorMsg("語音辨識或評分失敗，可以重試評分或重新錄一次");
            setSessionState('scoreError');
        }
    };

    const startRecording = async () => {
        // iPhone 只允許「使用者點擊當下」啟動播放，所以必須在任何 await 之前先解鎖錄音播放器
        if (recordedAudioRef.current) {
            recordedAudioRef.current.src = SILENT_AUDIO;
            recordedAudioRef.current.play().then(() => recordedAudioRef.current?.pause()).catch(() => {});
        }
        if (speechAudioRef.current) {
            const speechEl = speechAudioRef.current;
            speechEl.onended = null;
            speechEl.src = SILENT_AUDIO;
            speechEl.play().then(() => speechEl.pause()).catch(() => {});
        }
        setErrorMsg(null);
        try {
            const stream = await navigator.mediaDevices.getUserMedia({ audio: true, video: false });
            streamRef.current = stream;
            
            const mimeType = getSupportedMimeType();
            const mediaRecorder = new MediaRecorder(stream, mimeType ? { mimeType } : undefined);
            mediaRecorderRef.current = mediaRecorder;
            audioChunksRef.current = [];
            silenceTimerRef.current = 0;

            const AudioContextClass = window.AudioContext || (window as any).webkitAudioContext;
            const audioCtx = new AudioContextClass();
            audioContextRef.current = audioCtx;

            const source = audioCtx.createMediaStreamSource(stream);
            sourceRef.current = source;
            const analyser = audioCtx.createAnalyser();
            analyser.fftSize = 256;
            analyserRef.current = analyser;
            source.connect(analyser);

            mediaRecorder.ondataavailable = (e) => {
                if (e.data.size > 0) {
                    audioChunksRef.current.push(e.data);
                }
            };

            mediaRecorder.onstop = () => {
                cleanupAudio();
                const durationSec = (Date.now() - recordingStartTimeRef.current) / 1000;
                const blob = new Blob(audioChunksRef.current, { type: mediaRecorder.mimeType || 'audio/webm' });
                lastRecordingRef.current = { blob, durationSec };
                runScoring(blob, durationSec);
            };

            mediaRecorder.start();
            recordingStartTimeRef.current = Date.now();
            setSessionState('recording');
            monitorVolume();

        } catch (err: any) {
            console.error("Recording error:", err);
            setErrorMsg("無法取得麥克風權限");
            setSessionState('idle');
        }
    };

    const handleReplayPrompt = () => {
        if (promptAudioUrl) {
            recordedAudioRef.current?.pause();
            playSpeech(promptAudioUrl);
        }
    };

    const handleReplayAnswer = () => {
        recordedAudioRef.current?.pause();
        if (answerAudioUrlRef.current) {
            playSpeech(answerAudioUrlRef.current);
        }
    };

    const handleReplayRecording = () => {
        stopSpeech();
        if (recordedAudioRef.current) {
            recordedAudioRef.current.currentTime = 0;
            recordedAudioRef.current.play().catch(() => {});
        }
    };

    const handleRetry = () => {
        stopSpeech();
        if (recordedAudioRef.current) {
            recordedAudioRef.current.pause();
        }
        lastRecordingRef.current = null;
        if (playbackUrlRef.current) {
            URL.revokeObjectURL(playbackUrlRef.current);
            playbackUrlRef.current = null;
        }
        setErrorMsg(null);
        setScoreResult(null);
        setUserText('');
        setTierBlockInfo(null);
        setSessionState('idle');
        initPrompt();
    };

    return (
        <div className="flex flex-col h-full bg-slate-50 dark:bg-slate-950 p-6 overflow-y-auto pb-20">
            <audio ref={recordedAudioRef} className="hidden" preload="auto" />
            <audio ref={speechAudioRef} className="hidden" preload="auto" />
            <div className="flex items-center gap-4 mb-8">
                <button 
                    onClick={onBack}
                    className="p-2 bg-white dark:bg-slate-900 text-slate-600 dark:text-slate-300 rounded-full shadow-sm hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors"
                >
                    <ChevronLeft size={24} />
                </button>
                <div className="flex-1">
                    <h2 className="text-xl font-black text-slate-800 dark:text-white line-clamp-1">
                        念出來練習
                    </h2>
                    {progressLabel && (
                        <p className="text-sm text-slate-500 dark:text-slate-400">
                            {progressLabel}
                        </p>
                    )}
                </div>
            </div>

            {!isPromptReady ? (
                <div className="bg-white dark:bg-slate-900 rounded-2xl p-8 shadow-sm border border-slate-200 dark:border-slate-800 flex flex-col items-center text-center">
                    {promptStatus === 'error' ? (
                        <>
                            <p className="text-red-500 dark:text-red-400 font-bold mb-6">
                                {promptError || '產生題目失敗，請稍後再試'}
                            </p>
                            <div className="flex flex-wrap gap-3 justify-center">
                                <button
                                    onClick={generatePrompts}
                                    className="px-5 py-2.5 bg-indigo-600 text-white rounded-xl font-bold shadow-md hover:bg-indigo-700 transition-colors"
                                >
                                    再試一次
                                </button>
                                <button
                                    onClick={isLastSentence ? onBack : onNext}
                                    className="px-5 py-2.5 bg-white dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 rounded-xl font-bold hover:bg-slate-50 dark:hover:bg-slate-700 transition-colors"
                                >
                                    跳過這題
                                </button>
                                <button
                                    onClick={onBack}
                                    className="px-5 py-2.5 bg-white dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 rounded-xl font-bold hover:bg-slate-50 dark:hover:bg-slate-700 transition-colors"
                                >
                                    返回
                                </button>
                            </div>
                        </>
                    ) : (
                        <div className="flex flex-col items-center py-4">
                            <Loader2 size={32} className="animate-spin text-indigo-600 dark:text-indigo-400 mb-3" />
                            <p className="text-slate-800 dark:text-slate-100 font-black text-lg mb-1">
                                正在準備題目…
                            </p>
                            <p className="text-xs text-slate-400 dark:text-slate-500 font-medium">
                                第一次練習這句需要幾秒鐘
                            </p>
                        </div>
                    )}
                </div>
            ) : (
                <>
                    <div className="bg-indigo-50 dark:bg-indigo-900/20 border border-indigo-100 dark:border-indigo-800 rounded-2xl p-6 mb-8 flex flex-col items-center">
                        {activePromptType === 'qaQuestion' && (
                            <>
                                <p className="text-sm font-bold text-indigo-600 dark:text-indigo-400 mb-2">回答這個問題：</p>
                                <p className="text-xl font-black text-slate-800 dark:text-slate-100 text-center">{sentenceObj.qaQuestion || generatedPrompts?.qaQuestion}</p>
                            </>
                        )}
                        {activePromptType === 'situationalPrompt' && (
                            <>
                                <p className="text-sm font-bold text-indigo-600 dark:text-indigo-400 mb-2">情境任務：</p>
                                <p className="text-xl font-black text-slate-800 dark:text-slate-100 text-center">{sentenceObj.situationalPrompt || generatedPrompts?.situationalPrompt}</p>
                            </>
                        )}
                        {activePromptType === 'imageUrl' && (
                            <>
                                <p className="text-sm font-bold text-indigo-600 dark:text-indigo-400 mb-4">看圖說出對應的句子：</p>
                                <img src={sentenceObj.imageUrl} alt="情境圖" className="max-w-full h-48 object-cover rounded-xl" referrerPolicy="no-referrer" />
                            </>
                        )}
                        {(activePromptType === 'qaQuestion' || activePromptType === 'situationalPrompt') && (
                            <button
                                type="button"
                                onClick={handleReplayPrompt}
                                disabled={!promptAudioUrl}
                                className="mt-4 flex items-center gap-1.5 px-3 py-1.5 text-xs font-bold bg-white dark:bg-slate-900 text-indigo-600 dark:text-indigo-400 border border-indigo-200 dark:border-indigo-800/60 rounded-xl shadow-sm transition-all disabled:opacity-50 disabled:cursor-not-allowed"
                            >
                                {promptAudioLoading ? (
                                    <>
                                        <Loader2 size={14} className="animate-spin" />
                                        <span>語音準備中…</span>
                                    </>
                                ) : promptAudioUrl ? (
                                    <>
                                        <Volume2 size={14} />
                                        <span>播放題目</span>
                                    </>
                                ) : (
                                    <>
                                        <Volume2 size={14} />
                                        <span>語音暫時無法使用</span>
                                    </>
                                )}
                            </button>
                        )}
                    </div>

                    {errorMsg && (
                        <div className="bg-red-50 dark:bg-red-900/20 text-red-600 dark:text-red-400 text-sm px-4 py-3 rounded-xl border border-red-100 dark:border-red-800 font-bold mb-6 text-center">
                            {errorMsg}
                        </div>
                    )}

                    {sessionState === 'idle' && (
                        <div className="flex flex-col items-center mt-4">
                            <button
                                onClick={startRecording}
                                className="w-20 h-20 bg-indigo-600 text-white rounded-full shadow-lg hover:bg-indigo-700 hover:scale-105 active:scale-95 transition-all flex items-center justify-center"
                            >
                                <Mic size={32} />
                            </button>
                            <button
                                type="button"
                                onClick={generatePrompts}
                                disabled={promptStatus === 'generating'}
                                className="mt-3 flex items-center gap-1.5 text-xs font-bold text-slate-500 dark:text-slate-400 hover:text-indigo-600 dark:hover:text-indigo-400 transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
                            >
                                {promptStatus === 'generating' ? (
                                    <>
                                        <Loader2 size={14} className="animate-spin" />
                                        <span>產生中…</span>
                                    </>
                                ) : (
                                    <>
                                        <RefreshCw size={14} />
                                        <span>換一組題目</span>
                                    </>
                                )}
                            </button>
                            {promptStatus === 'error' && promptError && (
                                <p className="text-xs text-red-500 dark:text-red-400 font-bold mt-1 text-center">
                                    {promptError}
                                </p>
                            )}
                        </div>
                    )}

                    {sessionState === 'scoreError' && (
                        <div className="flex flex-col sm:flex-row gap-3 mt-4">
                            <button
                                onClick={handleRetry}
                                className="flex-1 py-4 bg-white dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 rounded-xl font-bold hover:bg-slate-50 dark:hover:bg-slate-700 transition-colors flex items-center justify-center gap-2"
                            >
                                <RefreshCw size={18} />
                                重新錄一次
                            </button>
                            <button
                                onClick={() => {
                                    if (lastRecordingRef.current) {
                                        runScoring(lastRecordingRef.current.blob, lastRecordingRef.current.durationSec);
                                    }
                                }}
                                className="flex-1 py-4 bg-indigo-600 text-white rounded-xl font-bold shadow-md hover:bg-indigo-700 transition-colors flex items-center justify-center gap-2"
                            >
                                <RefreshCw size={18} />
                                重試評分
                            </button>
                        </div>
                    )}

                    {sessionState === 'recording' && (
                        <div className="flex flex-col items-center justify-center mt-4 gap-4">
                            <div className="w-20 h-20 bg-red-500 text-white rounded-full shadow-lg animate-pulse flex items-center justify-center">
                                <Mic size={32} />
                            </div>
                            <p className="text-sm font-bold text-red-500">聆聽中... (講完自動停止)</p>
                        </div>
                    )}

                    {sessionState === 'scoring' && (
                        <div className="flex flex-col items-center justify-center mt-4 gap-4">
                            <div className="w-20 h-20 bg-amber-500 text-white rounded-full shadow-lg flex items-center justify-center">
                                <Loader2 size={32} className="animate-spin" />
                            </div>
                            <p className="text-sm font-bold text-amber-600 dark:text-amber-500">分析語音與評分中...</p>
                        </div>
                    )}

                    {sessionState === 'scored' && scoreResult && (
                        <div className="bg-white dark:bg-slate-900 rounded-2xl p-6 shadow-sm border border-slate-200 dark:border-slate-800 animate-in fade-in slide-in-from-bottom-4 duration-500">
                            <div className="flex items-center justify-center gap-4 mb-6">
                                <div className="text-center">
                                    <div className="text-4xl font-black text-indigo-600 dark:text-indigo-400">
                                        {scoreResult.total}
                                    </div>
                                    <div className="text-xs font-bold text-slate-500 mt-1">總分</div>
                                </div>
                                <div className="h-12 w-px bg-slate-200 dark:bg-slate-700"></div>
                                <div className="flex gap-4">
                                    <div className="text-center">
                                        <div className="text-xl font-bold text-slate-700 dark:text-slate-300">{scoreResult.pronunciation}</div>
                                        <div className="text-[10px] font-bold text-slate-500">發音</div>
                                    </div>
                                    <div className="text-center">
                                        <div className="text-xl font-bold text-slate-700 dark:text-slate-300">{scoreResult.fluency}</div>
                                        <div className="text-[10px] font-bold text-slate-500">流暢</div>
                                    </div>
                                    <div className="text-center">
                                        <div className="text-xl font-bold text-slate-700 dark:text-slate-300">{scoreResult.stress}</div>
                                        <div className="text-[10px] font-bold text-slate-500">重音</div>
                                    </div>
                                </div>
                            </div>
                            
                            <div className="space-y-4 mb-6">
                                <div className="bg-slate-50 dark:bg-slate-950 p-4 rounded-xl border border-slate-100 dark:border-slate-800">
                                    <p className="text-xs font-bold text-slate-500 mb-1">目標原句</p>
                                    <p className="font-bold text-slate-800 dark:text-slate-200">{sentenceObj.text}</p>
                                </div>
                                <div className="bg-slate-50 dark:bg-slate-950 p-4 rounded-xl border border-slate-100 dark:border-slate-800">
                                    <p className="text-xs font-bold text-slate-500 mb-1">您的發音 (語音辨識)</p>
                                    <p className="font-bold text-slate-800 dark:text-slate-200">{userText}</p>
                                </div>
                                {hasAnswerAudio && (
                                    <button
                                        onClick={handleReplayAnswer}
                                        className="w-full py-4 bg-indigo-50 dark:bg-indigo-900/30 text-indigo-600 dark:text-indigo-400 border border-indigo-100 dark:border-indigo-800 rounded-xl font-bold hover:bg-indigo-100 dark:hover:bg-indigo-900/50 transition-colors flex items-center justify-center gap-2"
                                    >
                                        <Volume2 size={18} />
                                        重播正確答案
                                    </button>
                                )}
                                <button
                                    onClick={handleReplayRecording}
                                    className="w-full py-4 bg-white dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 rounded-xl font-bold hover:bg-slate-50 dark:hover:bg-slate-700 transition-colors flex items-center justify-center gap-2"
                                >
                                    <Play size={18} />
                                    重播我的錄音
                                </button>
                            </div>

                            <div className="flex items-center justify-between mb-2 px-2">
                                <span className="text-sm font-bold text-slate-600 dark:text-slate-400">目前熟練度</span>
                                <span className="text-sm font-black text-indigo-600 dark:text-indigo-400">{currentMastery} / 1000</span>
                            </div>
                            {tierBlockInfo?.blocked && (
                                <div className="bg-amber-50 dark:bg-amber-900/20 border border-amber-200 dark:border-amber-800 rounded-xl p-3 mb-8 text-amber-700 dark:text-amber-400 text-sm font-bold text-center">
                                    已到目前階段練習上限，{tierBlockInfo.waitDays}天後可以繼續往上練習到更高分
                                </div>
                            )}
                            {!tierBlockInfo?.blocked && <div className="mb-8"></div>}

                            <div className="flex flex-col sm:flex-row gap-3">
                                <button
                                    onClick={handleRetry}
                                    className="flex-1 py-4 bg-white dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 rounded-xl font-bold hover:bg-slate-50 dark:hover:bg-slate-700 transition-colors flex items-center justify-center gap-2"
                                >
                                    <RefreshCw size={18} />
                                    再念一次
                                </button>
                                
                                {isLastSentence ? (
                                    <button
                                        onClick={onNext} // Should be a finish handler if it's the last sentence
                                        className="flex-1 py-4 bg-green-600 text-white rounded-xl font-bold shadow-md hover:bg-green-700 transition-colors flex items-center justify-center gap-2"
                                    >
                                        <Check size={18} />
                                        完成練習
                                    </button>
                                ) : (
                                    <button
                                        onClick={onNext}
                                        className="flex-1 py-4 bg-indigo-600 text-white rounded-xl font-bold shadow-md hover:bg-indigo-700 transition-colors flex items-center justify-center gap-2"
                                    >
                                        下一句
                                        <ChevronRight size={18} />
                                    </button>
                                )}
                            </div>
                        </div>
                    )}
                </>
            )}
        </div>
    );
}
